#data cleaning:
#1: resize to make it easier for the computer to handle.
#2: make sure that the nueral network is not overfitting by making it realize a plant's state upside down or rotated.
#3: rescale the range of pixel intensity because computers like lower numbers.

import tensorflow as tf
from tensorflow.keras import layers, models
#names each image based on the folder names in batches of 32 random images so there is no bias created and for optimal efficiency, and decreases image size from 1000 by 1000 pixels to 128 by 128
train_ds = tf.keras.preprocessing.image_dataset_from_directory("plantdisease/plantvillage/PlantVillage", shuffle = True, image_size = (128,128), batch_size = 32,validation_split=0.3,subset="training",seed = 42)
test_ds = tf.keras.preprocessing.image_dataset_from_directory("plantdisease/plantvillage/PlantVillage", shuffle = True, image_size = (128,128), batch_size = 32,validation_split=0.3,subset="validation",seed = 42)
class_names = train_ds.class_names
#Randomly rotates images to make sure the neural network is not overfitting the data.
data_augmentation = tf.keras.Sequential([ layers.RandomFlip("horizontal_and_vertical"),layers.RandomRotation(0.2)])
def prepare(ds, augment=False):
  # rescales without using the augmentation method and does it it using multiple CPU cores based on the number of CPU cores available
  ds = ds.map(lambda x, y: (x / 255.0, y), num_parallel_calls=tf.data.AUTOTUNE)  # rescales so the computer handles easier numbers with the same ration meaning the same colors
  if augment:
    ds = ds.map(lambda x, y: (data_augmentation(x, training=True), y), num_parallel_calls=tf.data.AUTOTUNE)

  return ds.prefetch(buffer_size=tf.data.AUTOTUNE)

train_ds = prepare(train_ds,augment=True)
test_ds = prepare(test_ds)

import matplotlib.pyplot as plt
import numpy as np
position = 0

plt.figure(figsize = (15,12))#15 pictures with 3 rows and 5 columns . . . 15 inches / 5 = 3 inches per width of pic . . . 12 inches/3 is 4 inches per length of pic.
found_classes = []
for image, label in train_ds.unbatch():
  index = label.numpy() #helps us keep track of which classes we have already displayed and helps us get the label as the title
  if index in found_classes:
    pass
  else:
    found_classes.append(index)
    position+=1
    plt.subplot(3,5,position) #creates a grid of 3 rows, 5 columns, and puts the image in one of the 15 positions created by the 3 rows and 5 columns. (position starts at 1 and goes from top left to bottom right)
    plt.imshow(image.numpy()) # draws the image in the specfied subplot
    plt.title(class_names[index])# creates a title above it based on the label
    plt.axis("off") # removes the x and y axis as well as the numbers on the axes

  if len(found_classes) == 15:
    break
plt.tight_layout() # makes sure that nothing is overlapping
plt.show() # puts the figure on the screen

from tensorflow.keras import layers, models
model = models.Sequential([
    # tells the model what types of images it should expect with the same pixel size and color scheme.
    layers.InputLayer(shape = (128,128,3)),

    layers.Conv2D(32,(3,3), activation="relu"), # fliters the first layer on the supposed input, 32 is the number of charaterstics we are trying to look for making it a relatively less complex filter.
    layers.MaxPooling2D((2,2)), #conserves RAM and prevents overfitting

    layers.Conv2D(64,(3,3),activation = "relu"),
    layers.MaxPooling2D((2,2)),

    layers.Conv2D(128,(3,3),activation = "relu"),
    layers.MaxPooling2D((2,2)),

    layers.Conv2D(256,(3,3),activation = "relu"),
    layers.MaxPooling2D((2,2)),

    layers.Flatten(),
    layers.Dense(256,activation = "relu"), #takes the long string of values from flatten and finds a complex relationship between them
    layers.Dropout(0.3), #Turns of 30 percent of the neurons during training forcing the remaining neurons to work harder basically stopping reliality on just one neuron
    layers.Dense(15,activation = "softmax") # takes all 15 classes and mathematically creates percentages for the likliness of the input being the type of one of the 15 subclasses
    ])

model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.0001),loss = "sparse_categorical_crossentropy",metrics=["accuracy"]) # How to measure the performance: adaptively updating weights, finds loss by comparing probability, and defining what we want to track which is the percentage rate of the test data or accuracy

history = model.fit(train_ds,epochs=10,validation_data=test_ds,verbose=1)

import matplotlib.pyplot as plt

# Extract accuracy data from the history object
acc = history.history["accuracy"]
val_acc = history.history["val_accuracy"]
epochs = range(1, len(acc) + 1)

# Create the graph
plt.plot(epochs, acc, "b", label="Training accuracy")
plt.plot(epochs, val_acc, "r", label="Validation accuracy")
plt.title("Training and Validation Accuracy")
plt.xlabel("Epochs")
plt.ylabel("Accuracy")
plt.legend()
plt.show()
